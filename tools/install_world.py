"""Copies a Minecraft world folder, keeping only the region files inside a region-coordinate box.
Chunks outside the box are regenerated by the world's own (superflat) generator when needed,
so an empty sea or sky costs nothing to drop.

    py tools/install_world.py <source world> <target folder> <rx_min> <rx_max> <rz_min> <rz_max>
"""
import os
import shutil
import sys

src, dst = sys.argv[1], sys.argv[2]
rx0, rx1, rz0, rz1 = map(int, sys.argv[3:7])
SKIP = {"session.lock", "uid.dat", "desktop.ini", "playerdata", "advancements", "stats", "DIM-1", "DIM1"}

if os.path.exists(dst):
    shutil.rmtree(dst)
os.makedirs(dst)
kept = dropped = 0
for name in os.listdir(src):
    if name in SKIP or (name.startswith("level") and name.endswith(".dat") and name not in ("level.dat", "level.dat_old")):
        continue
    s, d = os.path.join(src, name), os.path.join(dst, name)
    if name in ("region", "entities", "poi"):
        os.makedirs(d)
        for f in os.listdir(s):
            parts = f.split(".")
            if len(parts) == 4 and parts[3] == "mca":
                rx, rz = int(parts[1]), int(parts[2])
                if rx0 <= rx <= rx1 and rz0 <= rz <= rz1:
                    shutil.copy2(os.path.join(s, f), os.path.join(d, f))
                    kept += 1
                else:
                    dropped += 1
    elif os.path.isdir(s):
        shutil.copytree(s, d)
    else:
        shutil.copy2(s, d)
size = sum(os.path.getsize(os.path.join(b, f)) for b, _, fs in os.walk(dst) for f in fs)
print(f"{dst}: kept {kept} region/entity/poi files, dropped {dropped}, {size / 1e6:.1f} MB")
